// Optional: compile with the npm `solc` (solc-js) package instead of downloading a native compiler.
// Useful in sandboxes / CI without access to binaries.soliditylang.org:  SOLCJS=1 npx hardhat test
if (process.env.SOLCJS) {
  subtask(TASK_COMPILE_SOLIDITY_GET_SOLC_BUILD, async (args: { solcVersion: string }, _hre, runSuper) => {
    if (args.solcVersion === "0.8.27") {
      // eslint-disable-next-line @typescript-eslint/no-require-imports
      const solc = require("solc");
      return { compilerPath: require.resolve("solc/soljson.js"), isSolcJs: true, version: "0.8.27", longVersion: solc.version() };
    }
    return runSuper();
  });
}

